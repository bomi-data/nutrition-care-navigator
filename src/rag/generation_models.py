"""Typed data structures for the Grounded RAG Generation layer.

Role boundary (docs/rag_generation_v1_report.md §1-3): Claude is an
*explainer*, never a decision-maker. Every field that carries a decision --
which service, what score, what grade, what evidence exists, what's missing
-- is produced by Python (recommender + rag.retriever) and handed to Claude
as read-only input, or assembled by Python after Claude returns. Claude only
ever fills the free-text explanation fields on ``LLMGeneratedFields``, and
even those are sanitized afterward (see ``guardrails.py``).
"""

